#!/usr/bin/env python3
"""Build The Last Jug from oil/src/*.js.

  python3 tools/build-oil.py            writes oil/game.js (what oil/index.html loads)
  python3 tools/build-oil.py OUT.html   also writes a single self-contained page

The sources share one module scope, so they are concatenated in file-name order.
In the single page, three.js loads from jsDelivr, pinned to the version in vendor/three."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent / 'oil'
js = '\n'.join(p.read_text() for p in sorted((root / 'src').glob('*.js')))
(root / 'game.js').write_text('// Generated by tools/build-oil.py from oil/src/*.js. Do not edit by hand.\n' + js)
print(f'wrote oil/game.js ({len(js) // 1024} KB)')

if len(sys.argv) > 1:
    html = (root / 'index.html').read_text()
    css = (root / 'style.css').read_text()
    body = re.search(r'<!--APP START-->(.*)<!--APP END-->', html, re.S).group(1)
    fonts = re.search(r'<link rel="stylesheet" href="(https://fonts[^"]+)">', html).group(1)
    page_js = js.replace("'../vendor/three/three.module.min.js'", "'https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.min.js'")
    out = f'<title>The Last Jug</title>\n<link rel="stylesheet" href="{fonts}">\n<style>\n{css}\n</style>\n{body.strip()}\n<script type="module">\n{page_js}\n</script>\n'
    pathlib.Path(sys.argv[1]).write_text(out)
    print(f'wrote {sys.argv[1]} ({len(out) // 1024} KB)')
